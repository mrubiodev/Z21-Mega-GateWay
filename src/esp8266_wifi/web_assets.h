/*
 * web_assets.h
 * ------------
 * Assets estaticos del portal web, precomprimidos en gzip y guardados en
 * PROGMEM (flash), no en RAM. Responsabilidad unica de este archivo: dar
 * acceso a esos bytes -- no genera HTML ni conoce nada del protocolo Z21.
 *
 * Por que gzip + PROGMEM en vez de un String literal como el resto del
 * portal:
 *   - PROGMEM: los bytes viven en flash y se leen directamente desde ahi
 *     al servir la respuesta (server.send_P), sin copiarlos antes a un
 *     buffer en RAM como hace un String normal -- en el ESP8266 la RAM
 *     libre (~50KB) es mucho mas escasa que la flash, y es la que se
 *     fragmenta con las paginas dinamicas (log, sniffer). Esto no le come
 *     nada de esa RAM.
 *   - gzip: el CSS comprime de 2998 a 1126 bytes, el
 *     JS de 943 a 450. El ESP8266WebServer puede
 *     mandar el gzip tal cual con la cabecera Content-Encoding: gzip -- es
 *     el propio navegador quien lo descomprime, el ESP no tiene que
 *     hacerlo nunca.
 *
 * v0.18: añadidas reglas de tabla (table/th/td) e .inline-form, para el
 * panel /clients (lista de clientes Z21 con nombre editable).
 *
 * Para regenerar tras editar el CSS o el JS: ver el script Python al
 * final de este archivo.
 */

