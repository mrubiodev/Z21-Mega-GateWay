/*
 * web_assets.h
 * ------------
 * Assets estaticos del portal web, precomprimidos en gzip y guardados en
 * PROGMEM (flash), no en RAM. Responsabilidad unica de este archivo: dar
 * acceso a esos bytes -- no genera HTML ni conoce nada del protocolo Z21.
 *
 * Por que gzip + PROGMEM en vez de un String de CSS como el resto de
 * paginas:
 *   - PROGMEM: los bytes viven en flash y se leen directamente desde ahi
 *     al servir la respuesta (server.send_P), sin copiarlos antes a un
 *     buffer en RAM como hace un String normal -- en el ESP8266 la RAM
 *     libre (~50KB) es mucho mas escasa que la flash, y es la que se
 *     fragmenta con las paginas dinamicas (log, sniffer). Esto no le come
 *     nada de esa RAM.
 *   - gzip: el CSS combinado de todo el portal comprime de 455 a 282
 *     bytes (38% menos). El ESP8266WebServer puede mandar el gzip tal
 *     cual con la cabecera Content-Encoding: gzip -- es el propio
 *     navegador quien lo descomprime, el ESP no tiene que hacerlo nunca.
 *     (Con un CSS tan pequeño el ahorro de gzip es modesto por el
 *     overhead de cabecera del propio formato; según el portal vaya
 *     creciendo -- JS, mas paginas -- el porcentaje de ahorro sube.)
 *
 * Para regenerar tras editar el CSS: ver comentario al final de este
 * archivo con el script Python usado para generar el array de abajo.
 */

